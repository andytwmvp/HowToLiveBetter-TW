def normalize_reader_copy(body: str, *, include_v3: bool = False) -> tuple[str, list[str]]:
    """Remove review-workflow prose, retain reader-relevant limits, and rename headings.

    Source-linked reference paragraphs are left intact. Removed clauses remain in
    review records and Git history; this operation does not certify a new review.
    """
    if not isinstance(body, str):
        raise TypeError("讀者正文必須是文字")
    had_final_newline = body.endswith("\n")
    body = body.replace("燃氣熱水器使用戶數", "使用燃氣熱水器的家戶數")
    body = body.replace("燃氣設備使用戶數", "使用燃氣設備的家戶數")
    body = body.replace("未滿十四歲得用戶口名簿", "未滿十四歲可附戶口名簿")
    body = re.sub(r"(?<!使)用戶(?!口)", "使用者", body)
    body = re.sub(
        r"法規資料庫整編截至20\d{2}-\d{2}-\d{2}[；;]\s*之後的修正、個案資格及申辦期限，請向主管機關確認。",
        "法規可能更新，個案資格及申辦期限請向主管機關確認。",
        body,
    )
    for original, replacement in READER_COPY_REPLACEMENTS.items():
        body = body.replace(original, replacement)
    if include_v3:
        for original, replacement in READER_COPY_V3_REPLACEMENTS.items():
            body = body.replace(original, replacement)
    for original, replacement in READER_COPY_POST_REPLACEMENTS.items():
        body = body.replace(original, replacement)
    body = re.sub(r"截至查閱日[：，,]?\s*", "", body)
    body = re.sub(r"截至本次(?:查核|查閱)[，,]?\s*", "", body)
    body = re.sub(r"截至本次(?:查核|查閱)[，,]?\s*未找到", "目前沒有找到", body)
    body = re.sub(r"本(?:次|輪)(?:查核|查閱)?未找到", "目前沒有找到", body)
    body = re.sub(r"本(?:次|輪)(?:查核|查閱)?沒有找到", "目前沒有找到", body)
    body = re.sub(r"本(?:次|輪)(?:查核|查閱)?沒有(?=(?:可|同|全|合適|涵蓋|能|相同|一致))", "目前沒有", body)
    body = re.sub(
        r"本(?:次|輪)(?:查核|查閱)?未取得(?=.{0,100}(?:全國|全臺|全台|臺灣|台灣|同口徑|分母|母數|發生率|盛行率|統計資料))",
        "目前沒有",
        body,
    )
    body = re.sub(
        r"職業傷病診治專責或網絡醫院",
        "職業傷病診治專責醫院或網絡醫院",
        body,
    )
    paragraphs = re.split(r"\n\s*\n", body.strip("\n")) if body.strip("\n") else []
    removed: list[str] = []
    reader_paragraphs = []
    for paragraph in paragraphs:
        links: list[str] = []

        def keep_link(match: re.Match[str]) -> str:
            token = f"@@READER_LINK_{len(links)}@@"
            links.append(match.group(0))
            return token

        protected = re.sub(r"\[[^\]]+\]\(https?://[^)]+\)", keep_link, paragraph)
        audit_tail = READER_AUDIT_TAIL.search(protected)
        if (audit_tail or READER_PROCESS_CLAUSE.search(protected)
                or READER_EDITORIAL_TAIL.search(protected)):
            reader_limit = _reader_facing_tail(protected)
            if reader_limit != protected:
                removed.append(paragraph)
                if not reader_limit or READER_EDITORIAL_TAIL.search(reader_limit):
                    if not links:
                        continue
                    protected = "參考資料：" + "、".join(
                        f"@@READER_LINK_{index}@@" for index in range(len(links))
                    )
                else:
                    protected = reader_limit
                    missing_links = [
                        f"@@READER_LINK_{index}@@" for index in range(len(links))
                        if f"@@READER_LINK_{index}@@" not in protected
                    ]
                    if missing_links:
                        protected = protected.rstrip() + " 參考資料：" + "、".join(missing_links)
            elif READER_EDITORIAL_TAIL.search(protected) or audit_tail:
                removed.append(paragraph)
                if not links:
                    continue
                protected = "參考資料：" + "、".join(
                    f"@@READER_LINK_{index}@@" for index in range(len(links))
                )
            for index, link in enumerate(links):
                token = f"@@READER_LINK_{index}@@"
                protected = protected.replace(token, link)
            paragraph = protected
        else:
            for index, link in enumerate(links):
                protected = protected.replace(f"@@READER_LINK_{index}@@", link)
            paragraph = protected
        reader_paragraphs.append(REFERENCE_HEADINGS.get(paragraph, paragraph))
    cleaned = "\n\n".join(reader_paragraphs)
    # A process paragraph may be reduced to a dangling conjunction first; apply
    # exact reader-facing repairs once more to the retained clauses.
    for original, replacement in READER_COPY_REPLACEMENTS.items():
        cleaned = cleaned.replace(original, replacement)
    if include_v3:
        for original, replacement in READER_COPY_V3_REPLACEMENTS.items():
            cleaned = cleaned.replace(original, replacement)
    if had_final_newline and cleaned:
        cleaned += "\n"
    return cleaned, removed


def normalize_reader_item(item: dict) -> tuple[dict, list[str]]:
    """Normalize every field rendered by the website and offline editions."""
    if not isinstance(item, dict):
        raise TypeError("讀者條目必須是物件")
    cleaned = dict(item)
    removed: list[str] = []
    for field in ("title", "body", "limits", "question"):
        value = cleaned.get(field)
        if not isinstance(value, str):
            continue
        for original, replacement in READER_TITLE_REPLACEMENTS.items():
            value = value.replace(original, replacement)
        if field == "limits":
            for original, replacement in READER_LIMIT_REPLACEMENTS.items():
                value = value.replace(original, replacement)
        for _ in range(8):
            previous = value
            value, field_removed = normalize_reader_copy(value)
            removed.extend(f"{field}: {entry}" for entry in field_removed)
            if value == previous:
                break
        else:
            raise ValueError("讀者文字整理在八次內未收斂：" + str(item.get("id")))
        if field == "body" and cleaned.get("id") in READER_PROFESSIONAL_LIMITS:
            notice = READER_PROFESSIONAL_LIMITS[cleaned["id"]]
            if notice not in value:
                notice_followup = "若要處理個人醫療或保護需求，請向醫療團隊、社工或所在地主管機關確認。"
                if notice_followup in value:
                    value = value.replace(notice_followup, notice, 1)
                else:
                    heading = "## 參考資料"
                    if heading in value:
                        value = value.replace(heading, notice + "\n\n" + heading, 1)
                    else:
                        value = value.rstrip() + "\n\n" + notice + "\n"
        cleaned[field] = value
    return cleaned, removed


def normalize_reader_item_v3(item: dict) -> tuple[dict, list[str]]:
    """Apply the v2 reader-copy rules plus new editorial cleanup rules."""
    if not isinstance(item, dict):
        raise TypeError("讀者條目必須是物件")
    cleaned, removed = normalize_reader_item(item)
    for field in ("title", "body", "limits", "question"):
        value = cleaned.get(field)
        if not isinstance(value, str):
            continue
        for _ in range(8):
            previous = value
            value, field_removed = normalize_reader_copy(value, include_v3=True)
            removed.extend(f"{field}: {entry}" for entry in field_removed)
            if value == previous:
                break
        else:
            raise ValueError("讀者文字整理在八次內未收斂：" + str(item.get("id")))
        cleaned[field] = value
    return cleaned, removed


def _reader_fields_sha256(item: dict) -> str:
    fields = {key: item.get(key) for key in ("title", "body", "limits", "question") if key in item}
    payload = json.dumps(fields, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def make_reader_copy_cleanup_record(
    old: dict, new: dict, prior_revision: str, prior_review_sha256: str | None = None,
    transform: str = "reader_copy_cleanup_v2",
) -> dict:
    """Build an append-only history edge for reader-visible copy normalization."""
    return {
        "id": old["id"],
        "prior_revision": prior_revision,
        "transform": transform,
        "before_sha256": hashlib.sha256(old["body"].encode("utf-8")).hexdigest(),
        "after_sha256": hashlib.sha256(new["body"].encode("utf-8")).hexdigest(),
        "before_reader_sha256": _reader_fields_sha256(old),
        "after_reader_sha256": _reader_fields_sha256(new),
        "prior_review_sha256": prior_review_sha256,
    }


def _reader_facing_tail(paragraph: str) -> str:
    """Keep factual limits while removing dates and review-workflow clauses."""
    clauses = re.findall(r"[^。；，;]+[。；，;]?", paragraph)
    kept = [clause for clause in clauses if clause.strip() and not READER_PROCESS_CLAUSE.search(clause)]
    cleaned = "".join(kept).strip(" \t，；;")
    cleaned = re.sub(r"[；;]+(?=[。！？]|$)", "", cleaned)
    if cleaned and not cleaned.endswith(("。", "！", "？")):
        cleaned += "。"
    return cleaned


def documented_reader_cleanup(old: dict, new: dict, record: dict) -> bool:
    """Accept only a hash-checked normalization of trailing editorial notes."""
    if (not isinstance(old, dict) or not isinstance(new, dict) or not isinstance(record, dict)
            or old.get("id") != new.get("id") or record.get("id") != old.get("id")
            or record.get("transform") != "reader_copy_cleanup_v1"
            or not isinstance(old.get("body"), str) or not isinstance(new.get("body"), str)
            or old.get("body") == new.get("body")):
        return False
    if ({key: value for key, value in old.items() if key != "body"}
            != {key: value for key, value in new.items() if key != "body"}):
        return False
    cleaned, _removed = normalize_reader_copy(old["body"])
    before = hashlib.sha256(old["body"].encode("utf-8")).hexdigest()
    after = hashlib.sha256(new["body"].encode("utf-8")).hexdigest()
    return (cleaned == new["body"]
            and record.get("before_sha256") == before
            and record.get("after_sha256") == after)


def documented_reader_item_cleanup(old: dict, new: dict, record: dict) -> bool:
    if (not isinstance(old, dict) or not isinstance(new, dict) or not isinstance(record, dict)
            or old.get("id") != new.get("id") or record.get("id") != old.get("id")
            or record.get("transform") not in {"reader_copy_cleanup_v2", "reader_copy_cleanup_v3"}):
        return False
    normalize = normalize_reader_item_v3 if record["transform"] == "reader_copy_cleanup_v3" else normalize_reader_item
    normalized, _removed = normalize(old)
    return (
        normalized == new
        and record.get("before_sha256") == hashlib.sha256(old.get("body", "").encode("utf-8")).hexdigest()
        and record.get("after_sha256") == hashlib.sha256(new.get("body", "").encode("utf-8")).hexdigest()
        and record.get("before_reader_sha256") == _reader_fields_sha256(old)
        and record.get("after_reader_sha256") == _reader_fields_sha256(new)
    )


